-- 延迟拆成两个数：首字延迟与总耗时。
--
-- 一次调用只有一个「总耗时」时，账单解释不了体感：首字 300 ms + 8 秒生成，
-- 与首字 3 秒 + 1 秒生成，总耗时相近，体验完全不同，优化方向也不同（前者要调
-- 上游/预热，后者要缩输出或者换更快）。
--
-- first_token_ms：从请求发出到**第一个文本增量**到达的时刻。按真正的字算，
-- 不按第一帧算——OpenAI chat 的第一帧常常只有一个空的 delta.role，
-- DeepSeek 的推理模型会先吐 reasoning_content，它们都比第一个字早得多。
-- 非流式没有「首字」这个事件（整段一次到达），记 NULL：宁可空着，也不拿总耗时冒充。
ALTER TABLE requests ADD COLUMN first_token_ms INTEGER;
